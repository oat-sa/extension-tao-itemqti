define(['jquery', 'taoQtiItem/qtiCreator/widgets/helpers/comments'], function ($, comments) {
    'use strict';

    QUnit.module('comments');

    QUnit.test('module', function (assert) {
        assert.expect(2);

        assert.ok(typeof comments === 'object', 'The module exposes an object');
        assert.ok(
            typeof comments.wrapWithAutogeneratedComment === 'function',
            'The module exposes a wrapWithAutogeneratedComment function'
        );
    });

    QUnit.module('comments.wrapWithAutogeneratedComment');

    QUnit.test('does not throw for an empty container', function (assert) {
        assert.expect(1);

        //widgets of elements that are not in the document yet (e.g. math inside
        //an inline choice, whose markup is only inserted once the interaction
        //widget is built) are built on an empty container: wrapping it with the
        //autogenerated code comments must be a no-op instead of an error
        comments.wrapWithAutogeneratedComment($('.does-not-exist'));

        assert.ok(true, 'No error was thrown for an empty container');
    });

    QUnit.test('wraps a container that is in the document', function (assert) {
        const $fixture = $('#fixture');
        const $element = $fixture.find('.element');

        assert.expect(3);

        comments.wrapWithAutogeneratedComment($element);

        assert.ok($element[0].previousSibling.nodeType === Node.COMMENT_NODE, 'A start comment was added before');
        assert.ok($element[0].nextSibling.nodeType === Node.COMMENT_NODE, 'An end comment was added after');

        comments.wrapWithAutogeneratedComment($element);

        assert.equal(
            $fixture.contents().filter(function () {
                return this.nodeType === Node.COMMENT_NODE;
            }).length,
            2,
            'Wrapping an already wrapped container does not duplicate the comments'
        );
    });
});
